`timescale 1ns / 1ps

// Верхний уровень для платы Sipeed Tang Nano 20K (GW2AR-LV18QN88C8/I7)
// Оборачивает SG_LAB5_TOP без изменения логики (изначально работа бдолжна была сдаваться на плате nexys A7, но затем переведена на собственную ПЛИС для удобства):
//   - тактовая частота 27 МГц (параметр CLK_FREQ)
//   - кнопка S1 (pin 88) активна в "1" -> инвертируется в SYS_NRST
//   - 6 светодиодов (pin 15..20) горят от "0" -> LED[5:0] инвертируются
//   - LED[7:0] дополнительно выведены на внешние пины ext_led (активный уровень 1)
module SG_LAB5_TN20K(
    input clk,           //27 МГц, pin 4
    input rst,           //кнопка S1, pin 88, нажата = 1
    input uart_rx,       //pin 70, от USB-UART (BL616) к ПЛИС
    output uart_tx,      //pin 69, от ПЛИС к USB-UART
    output [5:0] led,    //pin 15..20, активный уровень 0 (светодиоды платы)
    output [7:0] ext_led //внешние светодиоды: 76, 80, 42, 41, 56, 54, 51, 48 (активный уровень 1)
);

wire [7:0] LED;

//ядро проекта, тактируется от 27 МГц
SG_LAB5_TOP #(.CLK_FREQ(27_000_000)) CORE (
    .CLK(clk),
    .SYS_NRST(~rst),    //инвертируем кнопку: нажата = сброс
    .UART_RXD(uart_rx),
    .UART_TXD(uart_tx),
    .LED(LED)
);

assign led = ~LED[5:0];  //на плате светодиоды активны нулём
assign ext_led = LED;    //pin -> резистор -> светодиод -> GND

endmodule
